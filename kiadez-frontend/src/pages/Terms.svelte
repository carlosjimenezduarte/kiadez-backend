        <p>
          Kiadez.com es una plataforma digital sin ánimo de lucro creada por Carlos Jiménez Duarte con el propósito de
          ofrecer un espacio donde los usuarios puedan expresar deseos, reflexionar sobre ellos y participar en una
          dinámica comunitaria basada en el servicio voluntario.
