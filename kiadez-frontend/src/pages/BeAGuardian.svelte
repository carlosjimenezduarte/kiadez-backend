        <header class="content-header">
          <h1 class="content-title">La Filosofía del Buen Guardián</h1>
          <p class="content-subtitle">
            Inspirada en las Bienaventuranzas del <strong>Gran Maestro Jesús</strong>
          </p>
        </header>

        <section class="guardian-code">

          <div class="guardian-principle">
            <h2 class="principle-title">1. Lealtad a la Fuente</h2>
            <p class="principle-body">
              Jurarás lealtad al Guardián Supremo Absoluto, reconociendo que solo Él es la Fuente de toda plenitud y que
              ningún Guardián humano cumple deseos por sí mismo, sino que sirve como instrumento consciente de la
              Verdad.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los pobres de espíritu, porque de ellos es el Reino de los Cielos.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">2. Servicio desinteresado</h2>
            <p class="principle-body">
              Reconocerás que tu verdadera misión no es el reconocimiento ni la recompensa terrenal, sino el servicio
              silencioso y sincero, conforme a la enseñanza del Gran Maestro Jesús: dar sin hacer trompeta y obrar en lo
              secreto (Mateo 6, 1–8).
            </p>
            <p class="principle-beatitude">
              Bienaventurados los mansos, porque heredarán la tierra.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">3. Franqueza y honestidad</h2>
            <p class="principle-body">
              Actuarás con claridad, transparencia y verdad en cada decisión, evitando la manipulación, el engaño o las
              dobles intenciones. El Guardián no confunde, no promete lo que no puede sostener y no actúa desde la
              ambigüedad.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los de corazón limpio, porque ellos verán a Dios.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">4. Valentía frente a la injusticia</h2>
            <p class="principle-body">
              Tendrás la valentía de decir no cuando sea necesario, de proteger a los vulnerables y de enfrentar
              conductas injustas, aun cuando ello implique incomodidad, pérdida de aprobación o sacrificio personal.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los que tienen hambre y sed de justicia, porque serán saciados.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">5. Honor y coherencia</h2>
            <p class="principle-body">
              Mantendrás coherencia entre lo que piensas, sientes y haces. El honor del Guardián no proviene de su
              rango,
              sino de su fidelidad cotidiana a los valores que proclama.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los que trabajan por la paz, porque serán llamados hijos de Dios.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">6. Confianza en la Vida Eterna</h2>
            <p class="principle-body">
              No actuarás desde el miedo a la pérdida, al fracaso o a la muerte. El Buen Guardián sirve con libertad
              porque confía en que la vida trasciende lo visible y que ningún acto justo se pierde.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los perseguidos por causa de la justicia, porque de ellos es el Reino de los Cielos.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">7. Respeto absoluto por la dignidad humana</h2>
            <p class="principle-body">
              Jamás usarás al prójimo como mercancía emocional. No convertirás el dolor, la necesidad o el deseo ajeno
              en
              escenario, contenido o medio para tu propio beneficio. Concederás deseos como intermediario consciente,
              sabiendo que tu verdadera recompensa no es pública, sino espiritual y vital.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los misericordiosos, porque alcanzarán misericordia.
            </p>
          </div>

          <div class="guardian-principle">
            <h2 class="principle-title">8. Discernimiento y responsabilidad</h2>
            <p class="principle-body">
              Aprobarás y concederás deseos de manera consciente y libre, sin presión, sin culpa y sin lástima. No
              actuarás
              por caridad superficial, sino por coherencia profunda con la Verdad y con la Gran Obra que has aceptado
              custodiar.
            </p>
            <p class="principle-beatitude">
              Bienaventurados los que lloran, porque serán consolados.
              <span class="principle-note">(Quien ha conocido el dolor, discierne mejor el acto justo.)</span>
            </p>
          </div>

